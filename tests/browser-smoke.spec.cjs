const {test,expect}=require('@playwright/test');
const url='http://127.0.0.1:4173';
test.use({viewport:{width:1366,height:800}});
test('Rota and Van Allocation keep the sidebar and grid responsive',async({page})=>{
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(url+'/rota.html',{waitUntil:'domcontentloaded'});
  await expect(page.locator('#sheet-body tr').first()).toBeVisible({timeout:20000});
  await expect(page.locator('.besa-standalone-sidebar')).toBeVisible();
  await expect(page.locator('#besa-draft-bar')).toBeVisible();
  await page.locator('#next-4').click();
  await expect(page.locator('#range-title')).toContainText('W');
  await page.locator('#show-vans-tab').click();
  await expect(page.locator('#vans-tab-panel')).toBeVisible();
  await expect(page.locator('.besa-standalone-sidebar a[data-standalone-page="vans"]')).toHaveAttribute('aria-current','page');
  await page.locator('#show-rota-tab').click();
  await expect(page.locator('#rota-tab-panel')).toBeVisible();
  await expect(page.locator('#besa-speed-button')).toBeVisible();
  expect(errors).toEqual([]);
});
test('Payment Tracker draft edits survive failed secure load without backend migration',async({page})=>{
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(url+'/payment-tracker.html',{waitUntil:'domcontentloaded'});
  const cell=page.locator('[data-row="3"][data-col="4"]');
  await expect(cell).toBeVisible({timeout:15000});
  await cell.click();
  await page.keyboard.type('23');
  await expect(page.locator('#total-routes')).toHaveText('23');
  await page.getByRole('button',{name:'Load saved'}).click();
  await expect(page.locator('.besa-draft-message')).toContainText(/sign|connection|setup|administrator|load|installed|failed|unavailable/i,{timeout:20000});
  await expect(page.locator('#total-routes')).toHaveText('23');
  expect(errors).toEqual([]);
});
test('Navigation prefetch does not remove office sidebar on mobile',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto(url+'/rota.html',{waitUntil:'domcontentloaded'});
  await expect(page.locator('#sheet-body tr').first()).toBeVisible({timeout:20000});
  await expect(page.locator('.besa-standalone-sidebar nav')).toBeVisible();
  await page.locator('.besa-standalone-sidebar a[data-standalone-page="tracker"]').click();
  await expect(page).toHaveURL(/payment-tracker.html/);
  await expect(page.locator('.besa-standalone-sidebar nav')).toBeVisible();
  await expect(page.locator('#payment-grid')).toBeVisible();
});
